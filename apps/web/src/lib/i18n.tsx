export type MessageKey = keyof (typeof messages)['en']

interface I18nValue {
  language: Language
  setLanguage: (language: Language) => void
  /**
   * `values` fills `{name}` placeholders. Only a handful of strings carry one
   * (counts, mostly); everything else ignores the argument.
   */
  t: (key: MessageKey, values?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nValue | null>(null)

// Storage access can throw outright (e.g. sandboxed iframes with third-party
// storage blocked), so both accessors must stay non-fatal.
function readStoredLanguage(): string | null {
  try {
    return window.localStorage.getItem('dsh-1024store-language')
  } catch {
    return null
  }
}

function persistLanguage(language: Language) {
  try {
    window.localStorage.setItem('dsh-1024store-language', language)
  } catch {
    // The choice still applies for the current session.
  }
}

function initialLanguage(): Language {
  const stored = readStoredLanguage()
  if (stored === 'en' || stored === 'zh') return stored
  return window.navigator.language.toLocaleLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, updateLanguage] = useState<Language>(initialLanguage)
  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en'
  }, [language])
  const value = useMemo<I18nValue>(
    () => ({
      language,
      setLanguage(nextLanguage) {
        persistLanguage(nextLanguage)
        updateLanguage(nextLanguage)
      },
      t: (key, values) => {
        const template: string = messages[language][key]
        if (!values) return template
        return Object.entries(values).reduce(
          (text, [name, replacement]) => text.replace(`{${name}}`, String(replacement)),
          template,
        )
      },
    }),
    [language],
  )
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}

/** Relative time, coarse on purpose: an exact minute is noise in a feed. */
export function useRelativeTime(): (iso: string) => string {
  const { t, language } = useI18n()
  return useCallback((iso: string) => {
    const elapsed = Date.now() - Date.parse(iso)
    const minutes = Math.floor(elapsed / 60_000)
    if (minutes < 1) return t('justNow')
    if (minutes < 60) return t('minutesAgo', { n: minutes })
    const hours = Math.floor(minutes / 60)
    if (hours < 24) return t('hoursAgo', { n: hours })
    const days = Math.floor(hours / 24)
    if (days < 7) return t('daysAgo', { n: days })
    return new Date(iso).toLocaleDateString(language === 'zh' ? 'zh-CN' : 'en-US', {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
    })
  }, [language, t])
}
